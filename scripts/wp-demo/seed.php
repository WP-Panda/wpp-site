function wpp_seed_cat( $name, $taxonomy = 'category' ) {
	$t = term_exists( $name, $taxonomy );
	if ( ! $t ) {
		$t = wp_insert_term( $name, $taxonomy );
	}
	return is_array( $t ) ? (int) $t['term_id'] : (int) $t;
}

function wpp_seed_post( $type, $title, $content, $args = array() ) {
	$existing = get_page_by_path( sanitize_title( $title ), OBJECT, $type );
	if ( $existing ) {
		return $existing->ID;
	}
	$id = wp_insert_post( array_merge( array(
		'post_type'    => $type,
		'post_status'  => 'publish',
		'post_title'   => $title,
		'post_content' => $content,
		'post_excerpt' => $args['excerpt'] ?? '',
		'post_author'  => get_current_user_id() ?: 1,
	), $args['post'] ?? array() ) );
	foreach ( ( $args['meta'] ?? array() ) as $k => $v ) {
		update_post_meta( $id, $k, $v );
	}
	foreach ( ( $args['terms'] ?? array() ) as $tax => $term ) {
		$tid = wpp_seed_cat( $term, $tax );
		wp_set_object_terms( $id, array( $tid ), $tax );
	}
	return $id;
}

